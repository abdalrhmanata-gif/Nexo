const FALLBACK_REASON_CODE = "DECISION_DEPENDENCY_UNAVAILABLE";

export function normalizeMissionAuthorityReasonCode(sourceReasonCode) {
  if (typeof sourceReasonCode !== "string") return FALLBACK_REASON_CODE;
  const code = sourceReasonCode.trim();
  if (!/^[A-Z][A-Z0-9_]{2,90}$/.test(code)) return FALLBACK_REASON_CODE;
  if (Object.hasOwn(SOURCE_REASON_CODE_MAP, code)) return SOURCE_REASON_CODE_MAP[code];
  if (CANONICAL_REASON_CODE_SET.has(code)) return code;
  return FALLBACK_REASON_CODE;
}

export function isKnownMissionAuthoritySourceReasonCode(sourceReasonCode) {
  return typeof sourceReasonCode === "string"
    && Object.hasOwn(SOURCE_REASON_CODE_MAP, sourceReasonCode);
}
