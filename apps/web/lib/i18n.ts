// Translation tables and a plain lookup, kept out of the "use client" module so
// server components can translate too. LocalizedText covers text nodes; this
// covers everything a component cannot wrap — placeholder and aria-label
// attributes, and strings produced inside JSX expressions.

export type AppLanguage = "en" | "nb" | "ar" | "es" | "fr" | "de";

export const SUPPORTED_LANGUAGES: AppLanguage[] = ["en", "nb", "ar", "es", "fr", "de"];
export const LANGUAGE_COOKIE = "zavqera-language";
export const LANGUAGE_STORAGE_KEY = "zavqera-language";

/**
 * Substitute {token} placeholders in an already-translated string. Keeping the
 * token inside the dictionary entry lets each language put the value where its
 * own word order needs it, instead of concatenating around a fixed English
 * fragment.
 */
export function fill(text: string, values: Record<string, string | number>): string {
  return Object.entries(values).reduce(
    (out, [key, value]) => out.split(`{${key}}`).join(String(value)),
    text,
  );
}

export function isSupportedLanguage(value: string | null | undefined): value is AppLanguage {
  return Boolean(value && (SUPPORTED_LANGUAGES as string[]).includes(value));
}

